"""eval/results/results.md: generated from the stored results, never hand-edited.

Each eval run stores its measurements as JSON in the results directory, then
results.md is rendered again from every stored file:

    retrieval.json            table 1, the retrieval ablation (task eval -- --retrieval-only)
    end_to_end-<row>.json     table 2, one row each (task eval -- --config NAME [--no-router])
    ../human_grades.jsonl     the author's grades of sampled answers (task eval -- --grade)

A table or row whose file is missing is reported as not run. Rendering reads
only the stored files, so it is repeatable and makes no model call.
"""

import datetime
from collections import Counter
from collections.abc import Iterable, Mapping
from pathlib import Path

from vessel_mind.eval.grades import agreement_lines, grades_path_for, load_grades
from vessel_mind.eval.metrics import document, percentile
from vessel_mind.eval.records import (
    ROW_ORDER,
    NotRun,
    QuestionRecord,
    RowResults,
    load_rows,
    ordered,
    row_command,
)
from vessel_mind.eval.retrieval import LANGS, RetrievalAblation

RETRIEVAL_FILE = "retrieval.json"
RESULTS_FILE = "results.md"

LANG_NAMES = {"en": "English", "zh-Hant": "Traditional Chinese"}

# A costly misroute: a fast-path answer this far below the slow-only answer.
MISROUTE_MARGIN = 0.25
BASELINE_ROW = "slow-only"
_DASH = "—"


def store_retrieval(results_dir: Path, ablation: RetrievalAblation) -> Path:
    """Store table 1's measurements and regenerate results.md. Returns its path."""
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / RETRIEVAL_FILE).write_text(
        ablation.model_dump_json(indent=2) + "\n", encoding="utf-8"
    )
    return write_results(results_dir)


def write_results(results_dir: Path) -> Path:
    path = results_dir / RESULTS_FILE
    path.write_text(render_results(results_dir), encoding="utf-8")
    return path


def render_results(results_dir: Path) -> str:
    retrieval_path = results_dir / RETRIEVAL_FILE
    retrieval = (
        RetrievalAblation.model_validate_json(retrieval_path.read_text(encoding="utf-8"))
        if retrieval_path.exists()
        else None
    )
    rows = load_rows(results_dir) if results_dir.exists() else {}
    grades = load_grades(grades_path_for(results_dir))
    lines = [
        "<!-- Generated by `task eval`. Do not edit: change the code or the inputs and re-run. -->",
        "",
        "# vessel-mind eval results",
        "",
        *_retrieval_section(retrieval),
        "",
        *_end_to_end_section(rows),
        "",
        *agreement_lines(rows, grades),
    ]
    return "\n".join(lines) + "\n"


