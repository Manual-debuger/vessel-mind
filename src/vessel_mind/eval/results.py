def _end_to_end_section(rows: Mapping[str, RowResults | NotRun]) -> Iterable[str]:
    yield "## 2. End to end"
    yield ""
    names = ordered([*ROW_ORDER, *rows])
    run = [r for r in rows.values() if isinstance(r, RowResults)]
    if run:
        first = run[0]
        yield (
            "Each row asks every golden question once, as a new turn through the router, the "
            f"way the server answers it. Golden set `{first.golden_path}` (SHA-256 "
            f"`{first.golden_sha256[:12]}`). The `slow-only` row is `hosted` with the router "
            "off: every turn takes the slow path."
        )
        yield ""
    k = run[0].top_k if run else 5
    yield (
        f"| Row | Fast / slow model | Questions | recall@{k} | MRR@{k} | Answer score "
        "| Citation correctness | Turn p50 s | Turn p95 s | Tokens in / out "
        "| List-price cost (USD) |"
    )
    yield "|---|---|---|---|---|---|---|---|---|---|---|"
    notes: list[str] = []
    for name in names:
        row = rows.get(name)
        if isinstance(row, RowResults):
            yield _row_line(row)
            missing = row.questions_total - len(row.records)
            if row.stopped or missing:
                notes.append(
                    f"- **{name}** is *incomplete*: "
                    + (row.stopped or f"{missing} questions not yet run")
                    + f". Resume it with `{row_command(name)}`."
                )
            continue
        if isinstance(row, NotRun):
            models, reason = f"{row.fast_model} / {row.slow_model}", row.reason
        else:
            models = _DASH
            reason = f"no results are stored; run `{row_command(name)}`."
        yield f"| {name} | {models} | *not run* |" + f" {_DASH} |" * 8
        notes.append(f"- **{name}** was not run: {reason}")
    if notes:
        yield ""
        yield from notes
    yield ""
    yield (
        f"Questions: answered of the golden set; a failed question is counted, never dropped. "
        f"recall@{k}: the share of an answerable question's expected documents that the top "
        f"{k} of any search in the turn come from; MRR@{k}: 1 / the rank of the first result "
        "from an expected document in the turn's first search (both 0 when the turn did not "
        "search). Answer score: the share of key points the judge marks covered, averaged over "
        "the judged answers (rubric `eval/judge.md`). Citation correctness: the share of the "
        "sources the answers cite ([n] mapped to the latest search before it, as the console "
        "maps it) whose document is an expected source, checked by code; a citation in an "
        "answer to an unanswerable question is never correct. Turn latency: the wall time of "
        "the turn on this machine, provider retries included, less the time the eval waited "
        "to space its requests. Tokens: classification plus answer, thinking tokens counted "
        "as output. List-price cost: tokens × the provider's paid list price on the date "
        "shown; the run used the free tier, so nobody paid it. The judge's own tokens are "
        "not counted."
    )
    for row in run:
        if row.router:
            yield ""
            yield from _router_lines(row, rows.get(BASELINE_ROW))
    yield from _judge_lines(run)


def _row_line(row: RowResults) -> str:
    done = [r for r in row.records if not r.failed]
    failed = len(row.records) - len(done)
    missing = row.questions_total - len(row.records)
    gaps = [f"{failed} failed"] * bool(failed) + [f"{missing} not yet run"] * bool(missing)
    questions = f"{len(done)} of {row.questions_total}" + (f" ({', '.join(gaps)})" if gaps else "")
    models = f"{row.fast_model if row.router else 'router off'} / {row.slow_model}"

    answerable = [r for r in done if r.expected_sources]
    recall = _mean([_recall(r, row.top_k) for r in answerable])
    mrr = _mean([_reciprocal_rank(r, row.top_k) for r in answerable])

    scores = [s for r in done if (s := r.score) is not None]
    unjudged = len(done) - len(scores)
    score = _fixed(_mean(scores), 2) + (f" ({unjudged} not judged)" if unjudged else "")

    cited = [document(s) in r.expected_sources for r in done for s in r.turn.citations]
    citations = (
        f"{sum(cited) / len(cited):.2f} ({sum(cited)} of {len(cited)})"
        if cited
        else "n/a (no citations)"
    )

    latencies = [r.turn.latency_ms / 1000 for r in done]
    p50 = _fixed(percentile(latencies, 50), 1) if latencies else "n/a"
    p95 = _fixed(percentile(latencies, 95), 1) if latencies else "n/a"

    tokens_in = sum(
        r.turn.router_usage.input_tokens + r.turn.answer_usage.input_tokens for r in done
    )
    tokens_out = sum(
        u.output_tokens + u.thinking_tokens
        for r in done
        for u in (r.turn.router_usage, r.turn.answer_usage)
    )
    return (
        f"| {row.row} | {models} | {questions} | {_fixed(recall, 2)} | {_fixed(mrr, 2)} "
        f"| {score} | {citations} | {p50} | {p95} | {tokens_in:,} / {tokens_out:,} "
        f"| {_row_cost(row, done)} |"
    )


def _recall(record: QuestionRecord, k: int) -> float:
    found = {document(s) for search in record.turn.searches for s in search[:k]}
    expected = set(record.expected_sources)
    return len(expected & found) / len(expected)


def _reciprocal_rank(record: QuestionRecord, k: int) -> float:
    if not record.turn.searches:
        return 0.0
    for rank, source in enumerate(record.turn.searches[0][:k], start=1):
        if document(source) in record.expected_sources:
            return 1.0 / rank
    return 0.0


def _row_cost(row: RowResults, done: list[QuestionRecord]) -> str:
    total = 0.0
    dates: set[datetime.date] = set()
    missing: set[str] = set()
    self_hosted = priced = False
    for record in done:
        turn = record.turn
        for usage, model in (
            (turn.router_usage, turn.router_model),
            (turn.answer_usage, turn.answer_model),
        ):
            tokens = usage.input_tokens + usage.output_tokens + usage.thinking_tokens
            if model is None or tokens == 0:
                continue
            if model in row.self_hosted_models:
                self_hosted = True
            elif (price := row.prices.get(model)) is not None:
                priced = True
                dates.add(price.as_of)
                total += (
                    usage.input_tokens * price.input_usd_per_mtok
                    + (usage.output_tokens + usage.thinking_tokens) * price.output_usd_per_mtok
                ) / 1_000_000
            else:
                missing.add(model)
    return cost_cell(
        None if missing else total,
        dates=tuple(sorted(dates)),
        self_hosted=self_hosted,
        priced=priced,
        missing=tuple(sorted(missing)),
    )


def cost_cell(
    cost: float | None,
    *,
    dates: tuple[datetime.date, ...],
    self_hosted: bool,
    priced: bool,
    missing: tuple[str, ...],
) -> str:
    """The list-price cost as table 2 shows it. A missing price is never estimated."""
    if missing or cost is None:
        names = ", ".join(f"`{m}`" for m in missing)
        return f"not reported: no list price for {names} in config"
    electricity = "GPU electricity not measured"
    if not priced:
        return f"$0 ({electricity})" if self_hosted else "n/a"
    text = f"${cost:.4f} at list price, {', '.join(d.isoformat() for d in dates)}"
    return text + (f"; self-hosted models $0, {electricity}" if self_hosted else "")


def _router_lines(row: RowResults, baseline: RowResults | NotRun | None) -> Iterable[str]:
    done = [r for r in row.records if not r.failed and r.turn.route is not None]
    yield f"### Router: {row.row}"
    yield ""
    if not done:
        yield "No completed turns."
        return
    right = sum(r.turn.route == r.expected_route for r in done)
    fallbacks = Counter(r.turn.reason for r in done if r.turn.reason != "classified")
    yield (
        f"Router accuracy against `expected_route`: {right / len(done):.2f} "
        f"({right} of {len(done)} turns). A fallback counts as the slow route it took."
    )
    yield ""
    detail = ", ".join(f"{reason}: {n}" for reason, n in sorted(fallbacks.items()))
    yield f"Fallbacks to the slow path: {fallbacks.total()}" + (f" ({detail})." if detail else ".")
    yield ""
    yield "| Expected \\ routed | fast | slow |"
    yield "|---|---|---|"
    for expected in ("fast", "slow"):
        counts = [
            sum(r.expected_route == expected and r.turn.route == route for r in done)
            for route in ("fast", "slow")
        ]
        yield f"| {expected} | {counts[0]} | {counts[1]} |"
    yield ""
    yield from _misroute_lines(done, baseline)


def _misroute_lines(
    done: list[QuestionRecord], baseline: RowResults | NotRun | None
) -> Iterable[str]:
    if not isinstance(baseline, RowResults):
        yield "Costly misroutes: not computed: the slow-only row has not run."
        return
    slow = {r.id: r.score for r in baseline.records if not r.failed}
    costly: list[str] = []
    unpaired = 0
    for record in done:
        if record.turn.route != "fast":
            continue
        score, base = record.score, slow.get(record.id)
        if score is None or base is None:
            unpaired += 1
        elif base - score >= MISROUTE_MARGIN - 1e-9:
            costly.append(record.id)
    yield (
        f"Costly misroutes: {len(costly)}"
        + (f" ({', '.join(costly)})." if costly else ".")
        + (
            f" {unpaired} fast-path answers have no judged slow-only answer to compare with."
            if unpaired
            else ""
        )
        + f" A costly misroute is a fast-path answer scoring at least {MISROUTE_MARGIN} below "
        "the slow-only answer to the same question."
    )


def _family(model: str) -> str:
    """A model's family: the first part of its id (gemini-3.5-flash: gemini)."""
    return model.split("-", 1)[0].lower()


def _judge_lines(run: list[RowResults]) -> Iterable[str]:
    yield ""
    yield "### Judge"
    yield ""
    if not run:
        yield "No row has run, so no answer has been judged."
        return
    for judge in sorted({r.judge_model for r in run}):
        rows = [r for r in run if r.judge_model == judge]
        yield (
            f"Judge: `{judge}`, with the rubric `eval/judge.md`, for the rows "
            f"{', '.join(r.row for r in rows)}."
        )
        family = _family(judge)
        shared = [
            r.row
            for r in run
            if any(
                _family(m) == family
                for m in ((r.fast_model,) if r.router else ()) + (r.slow_model,)
            )
        ]
        yield ""
        if shared:
            itself = [r.row for r in run if judge in (r.fast_model, r.slow_model)]
            yield (
                f"The judge `{judge}` shares a model family (`{family}`) with the measured rows "
                f"{', '.join(shared)}, so its scores may favour them."
                + (f" It is itself a model of {', '.join(itself)}." if itself else "")
            )
        else:
            yield f"The judge `{judge}` shares no model family with a measured row."


def _mean(values: list[float]) -> float | None:
    return sum(values) / len(values) if values else None


def _retrieval_section(ablation: RetrievalAblation | None) -> Iterable[str]:
    yield "## 1. Retrieval ablation"
    yield ""
    if ablation is None:
        yield "*Not run*: run `task eval -- --retrieval-only`."
        return
    k = ablation.top_k
    pins = ", ".join(f"{p.name} `{p.commit[:7]}`" for p in ablation.corpus)
    yield (
        f"`task eval -- --retrieval-only`, {ablation.generated.isoformat()}. No LLM calls. "
        f"Golden set `{ablation.golden_path}` (SHA-256 `{ablation.golden_sha256[:12]}`); "
        f"corpus {pins}, {ablation.chunks} chunks."
    )
    yield ""
    yield (
        f"Embedding model `{ablation.embedding_model}`; reranker `{ablation.reranker_model}` "
        f"(fastembed cross-encoder on CPU) over the top {ablation.candidate_k} hybrid "
        f"candidates. Every row returns the top {k}."
    )
    yield ""
    yield (
        f"recall@{k}: the share of a question's expected documents that a top-{k} result "
        f"comes from. MRR@{k}: 1 / the rank of the first top-{k} result from an expected "
        f"document (0 if none). Both are averaged over the questions with expected sources. "
        "Latency is one search's wall time on this machine's CPU (query embedding, candidate "
        "search and, in the rerank row, the cross-encoder), over every question, the "
        "unanswerable ones too; each row searches once before timing, so model loading is "
        "not counted."
    )
    for lang in LANGS:
        first = ablation.rows[0].languages[lang]
        noun = "question" if first.questions == 1 else "questions"
        yield ""
        yield (
            f"### {LANG_NAMES[lang]} ({first.questions} {noun} with expected sources, "
            f"{first.timed} timed)"
        )
        yield ""
        yield f"| Retrieval | recall@{k} | MRR@{k} | p50 ms | p95 ms |"
        yield "|---|---|---|---|---|"
        for row in ablation.rows:
            s = row.languages[lang]
            yield (
                f"| {row.name} | {_fixed(s.recall_at_k, 2)} | {_fixed(s.mrr, 2)} "
                f"| {_fixed(s.latency_ms_p50, 1)} | {_fixed(s.latency_ms_p95, 1)} |"
            )


def _fixed(value: float | None, digits: int) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"
