"""eval/results/results.md: generated from the stored results, never hand-edited.

Each eval run stores its measurements as JSON in the results directory, then
results.md is rendered again from every stored file:

    retrieval.json   table 1, the retrieval ablation (task eval -- --retrieval-only)

A table whose file is missing is reported as not run. Rendering reads only
the stored files, so it is repeatable and makes no model call.
"""

from collections.abc import Iterable
from pathlib import Path

from vessel_mind.eval.retrieval import LANGS, RetrievalAblation

RETRIEVAL_FILE = "retrieval.json"
RESULTS_FILE = "results.md"

LANG_NAMES = {"en": "English", "zh-Hant": "Traditional Chinese"}


def store_retrieval(results_dir: Path, ablation: RetrievalAblation) -> Path:
    """Store table 1's measurements and regenerate results.md. Returns its path."""
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / RETRIEVAL_FILE).write_text(
        ablation.model_dump_json(indent=2) + "\n", encoding="utf-8"
    )
    return write_results(results_dir)


def write_results(results_dir: Path) -> Path:
    path = results_dir / RESULTS_FILE
    path.write_text(render_results(results_dir), encoding="utf-8")
    return path


def render_results(results_dir: Path) -> str:
    retrieval_path = results_dir / RETRIEVAL_FILE
    retrieval = (
        RetrievalAblation.model_validate_json(retrieval_path.read_text(encoding="utf-8"))
        if retrieval_path.exists()
        else None
    )
    lines = [
        "<!-- Generated by `task eval`. Do not edit: change the code or the inputs and re-run. -->",
        "",
        "# vessel-mind eval results",
        "",
        *_retrieval_section(retrieval),
        "",
        "## 2. End to end",
        "",
        "*Not run*: the end-to-end eval (`task eval -- --config hosted|local|routed`) is not "
        "built yet.",
    ]
    return "\n".join(lines) + "\n"


def _retrieval_section(ablation: RetrievalAblation | None) -> Iterable[str]:
    yield "## 1. Retrieval ablation"
    yield ""
    if ablation is None:
        yield "*Not run*: run `task eval -- --retrieval-only`."
        return
    k = ablation.top_k
    pins = ", ".join(f"{p.name} `{p.commit[:7]}`" for p in ablation.corpus)
    yield (
        f"`task eval -- --retrieval-only`, {ablation.generated.isoformat()}. No LLM calls. "
        f"Golden set `{ablation.golden_path}` (SHA-256 `{ablation.golden_sha256[:12]}`); "
        f"corpus {pins}, {ablation.chunks} chunks."
    )
    yield ""
    yield (
        f"Embedding model `{ablation.embedding_model}`; reranker `{ablation.reranker_model}` "
        f"(fastembed cross-encoder on CPU) over the top {ablation.candidate_k} hybrid "
        f"candidates. Every row returns the top {k}."
    )
    yield ""
    yield (
        f"recall@{k}: the share of a question's expected documents that a top-{k} result "
        f"comes from. MRR@{k}: 1 / the rank of the first top-{k} result from an expected "
        f"document (0 if none). Both are averaged over the questions with expected sources. "
        "Latency is one search's wall time on this machine's CPU (query embedding, candidate "
        "search and, in the rerank row, the cross-encoder), over every question, the "
        "unanswerable ones too; each row searches once before timing, so model loading is "
        "not counted."
    )
    for lang in LANGS:
        first = ablation.rows[0].languages[lang]
        noun = "question" if first.questions == 1 else "questions"
        yield ""
        yield (
            f"### {LANG_NAMES[lang]} ({first.questions} {noun} with expected sources, "
            f"{first.timed} timed)"
        )
        yield ""
        yield f"| Retrieval | recall@{k} | MRR@{k} | p50 ms | p95 ms |"
        yield "|---|---|---|---|---|"
        for row in ablation.rows:
            s = row.languages[lang]
            yield (
                f"| {row.name} | {_fixed(s.recall_at_k, 2)} | {_fixed(s.mrr, 2)} "
                f"| {_fixed(s.latency_ms_p50, 1)} | {_fixed(s.latency_ms_p95, 1)} |"
            )


def _fixed(value: float | None, digits: int) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"
