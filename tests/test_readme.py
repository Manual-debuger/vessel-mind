"""The README a reviewer reads first (spec §7): its numbers come from results.md.

`eval/results/results.md` is generated by `task eval` and never hand-edited.
Each README (English, and Traditional Chinese) copies its tables between two
markers; these tests fail when a copy and the generated file differ, so no
README can drift from a run.
"""

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
README = REPO / "README.md"
README_ZH = REPO / "README.zh-TW.md"
READMES = pytest.mark.parametrize("readme_path", [README, README_ZH], ids=["en", "zh-TW"])
RESULTS = REPO / "eval" / "results" / "results.md"
CONSOLE = REPO / "src" / "vessel_mind" / "server" / "templates" / "console.html"

BEGIN = "<!-- results:begin -->"
END = "<!-- results:end -->"


def table_rows(text: str) -> list[str]:
    return [line.rstrip() for line in text.splitlines() if line.startswith("|")]


def results_section(readme: str) -> str:
    assert BEGIN in readme, f"README.md has no {BEGIN} marker"
    assert END in readme, f"README.md has no {END} marker"
    return readme.split(BEGIN, 1)[1].split(END, 1)[0]


@READMES
def test_every_results_table_row_in_the_readme_is_in_results_md(readme_path):
    copied = table_rows(results_section(readme_path.read_text(encoding="utf-8")))
    generated = set(table_rows(RESULTS.read_text(encoding="utf-8")))
    assert copied, "the README's results section has no table"
    missing = [row for row in copied if row not in generated]
    assert not missing, f"README rows not in results.md (re-copy them): {missing}"


@READMES
def test_the_readme_shows_every_results_table_row(readme_path):
    copied = set(table_rows(results_section(readme_path.read_text(encoding="utf-8"))))
    generated = table_rows(RESULTS.read_text(encoding="utf-8"))
    missing = [row for row in generated if row not in copied]
    assert not missing, f"results.md rows the README does not show: {missing}"


@READMES
def test_the_readme_quotes_the_judge_human_agreement_from_results_md(readme_path):
    results = RESULTS.read_text(encoding="utf-8")
    agreement = next(line for line in results.splitlines() if "Judge and author agree" in line)
    assert agreement in readme_path.read_text(encoding="utf-8")


@READMES
def test_the_readme_states_the_console_free_tier_notice(readme_path):
    template = CONSOLE.read_text(encoding="utf-8")
    match = re.search(r'id="free-tier">(.*?)</p>', template, re.DOTALL)
    assert match, "console.html has no free-tier notice"
    notice = " ".join(match.group(1).split())
    readme = " ".join(readme_path.read_text(encoding="utf-8").split())
    assert notice in readme


@READMES
def test_vessel_is_named_but_not_linked(readme_path):
    readme = readme_path.read_text(encoding="utf-8")
    assert re.search(r"\bVessel\b", readme), "the README does not name Vessel"
    links = re.findall(r"\[([^\]]*)\]\(([^)]*)\)", readme)
    vessel_links = [
        (text, url)
        for text, url in links
        if re.search(r"\bvessel\b(?!-mind)", f"{text} {url}", re.IGNORECASE)
    ]
    assert not vessel_links, f"the README links Vessel, which is private: {vessel_links}"


def heading_levels(readme: str) -> list[int]:
    levels, in_fence = [], False
    for line in readme.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        elif not in_fence and (match := re.match(r"(#+) ", line)):
            levels.append(len(match.group(1)))
    return levels


def test_the_translations_have_the_same_heading_structure():
    english = heading_levels(README.read_text(encoding="utf-8"))
    chinese = heading_levels(README_ZH.read_text(encoding="utf-8"))
    assert english == chinese, "README.zh-TW.md is out of step with README.md: update both"


def test_each_readme_links_the_other_language():
    assert "(README.zh-TW.md)" in README.read_text(encoding="utf-8")
    assert "(README.md)" in README_ZH.read_text(encoding="utf-8")
